import argparse
import io
import json
import re
import sys
import tarfile
import urllib.request
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[2]
TAG_RE = re.compile(r"^(\d+)\.(\d+)\.(\d+)-alpine(\d+)\.(\d+)$")
HEADER = "# generated by tool_version_checker.py - do not edit by hand\n"


def http_get(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "tool-version-checker"})
    with urllib.request.urlopen(req, timeout=30) as resp:
        return resp.read()


def latest_base_tag(image: str, max_pages: int = 10) -> str:
    repo = image if "/" in image else f"library/{image}"
    url = (
        f"https://hub.docker.com/v2/repositories/{repo}/tags?page_size=100&name=alpine"
    )
    best_key, best_tag = None, None
    for _ in range(max_pages):
        data = json.loads(http_get(url))
        for item in data["results"]:
            m = TAG_RE.match(item["name"])
            if m:
                key = tuple(int(x) for x in m.groups())
                if best_key is None or key > best_key:
                    best_key, best_tag = key, item["name"]
        url = data.get("next")
        if not url:
            break
    if not best_tag:
        sys.exit(f"No alpine tags found for {image}")
    return best_tag


def alpine_branch(tag: str) -> str:
    m = re.search(r"alpine(\d+\.\d+)", tag)
    if not m:
        sys.exit(f"Cannot find alpine version in tag '{tag}'")
    return f"v{m.group(1)}"


def load_index(branch: str, arch: str, mirror: str) -> dict:
    """Return {package: version} from the main + community indexes."""
    versions = {}
    for repo in ("main", "community"):
        url = f"{mirror}/{branch}/{repo}/{arch}/APKINDEX.tar.gz"
        with tarfile.open(fileobj=io.BytesIO(http_get(url)), mode="r:gz") as tar:
            text = tar.extractfile("APKINDEX").read().decode()
        for block in text.split("\n\n"):
            name = version = None
            for line in block.splitlines():
                if line.startswith("P:"):
                    name = line[2:]
                elif line.startswith("V:"):
                    version = line[2:]
            if name and version:
                versions[name] = version
    return versions


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("-i", "--input", type=Path, default=REPO_ROOT / "image.yaml")
    ap.add_argument(
        "-o", "--output", type=Path, default=REPO_ROOT / "updated_image.yaml"
    )
    ap.add_argument(
        "--arch", default="x86_64", help="apk architecture (x86_64, aarch64, ...)"
    )
    ap.add_argument(
        "--keep-base",
        action="store_true",
        help="keep the current base tag and only update packages within its Alpine release",
    )
    ap.add_argument("--mirror", default="https://dl-cdn.alpinelinux.org/alpine")
    args = ap.parse_args()

    cfg = yaml.safe_load(args.input.read_text())
    old_tag = cfg["base"]["tag"]

    if not args.keep_base:
        cfg["base"]["tag"] = latest_base_tag(cfg["base"]["image"])
    branch = alpine_branch(cfg["base"]["tag"])

    print(f"base: {old_tag} -> {cfg['base']['tag']}  (apk index: {branch}/{args.arch})")
    index = load_index(branch, args.arch, args.mirror)

    for name, old in cfg["packages"].items():
        newest = index.get(name)
        if old is None:
            if not newest:
                print(
                    f"  WARN {name}: not found in {branch}, leaving unpinned",
                    file=sys.stderr,
                )
                continue
            cfg["packages"][name] = newest
            print(f"  {name}: (unpinned) -> {newest}  [resolved to newest]")
        else:
            old = str(old)
            cfg["packages"][name] = old
            if not newest:
                print(
                    f"  WARN {name}: not found in {branch}, keeping pinned {old}",
                    file=sys.stderr,
                )
            elif newest == old:
                print(f"  {name}: {old} -> {old}  [pinned, already newest]")
            else:
                print(f"  {name}: {old} -> {old}  [pinned, kept; newest is {newest}]")

    args.output.write_text(HEADER + yaml.safe_dump(cfg, sort_keys=False))
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
